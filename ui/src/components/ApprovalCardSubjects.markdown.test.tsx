function render(markdown: string) {
  return renderToStaticMarkup(
    <QueryClientProvider client={new QueryClient()}>
      <ThemeProvider>
        <MarkdownBody>{markdown}</MarkdownBody>
      </ThemeProvider>
    </QueryClientProvider>,
  );
}

describe("approval card subjects in the real Markdown renderer", () => {
  it("the control: an unescaped hostile title does become a link", () => {
    expect(render("Delete [Open the post](https://evil.example) www.evil.example")).toMatch(/<a /);
  });

  it.each(SERVER_CARD_OUTPUT.map((card, index) => [index, card] as const))("server output %i renders with no links and no injected emphasis", (_index, card) => {
    const preview = render(card.preview);
    const summary = render(card.summary);
    expect(preview).not.toMatch(/<a /);
    expect(summary).not.toMatch(/<a /);
    expect((preview.match(/<strong>/g) ?? []).length).toBe(1);   // only the server's own headline
    expect(summary).not.toMatch(/<strong>/);
    expect(preview).not.toMatch(/<img/);
  });
});
